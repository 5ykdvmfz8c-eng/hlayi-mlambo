import { COMPANY, statementAmount } from "./company";
import { fmtDate, fmtDateTime } from "./format";

export type ReportColumn = { key: string; label: string; kind?: "text" | "money" | "date" };
export type ReportRow = Record<string, string | number | null>;
export type Report = {
  title: string;
  periodStart: string;
  periodEnd: string;
  columns: ReportColumn[];
  rows: ReportRow[];
  summary: { label: string; value: string }[];
  totals?: Record<string, number>;
};

export function cellText(col: ReportColumn, v: string | number | null | undefined): string {
  if (v == null || v === "") return "";
  if (col.kind === "money") return statementAmount(Number(v));
  if (col.kind === "date") return fmtDate(String(v));
  return String(v);
}

/** Sum each money column across rows. */
export function moneyTotals(columns: ReportColumn[], rows: ReportRow[]): Record<string, number> {
  const out: Record<string, number> = {};
  for (const c of columns) {
    if (c.kind !== "money") continue;
    out[c.key] = Math.round(rows.reduce((a, r) => a + Number(r[c.key] ?? 0), 0) * 100) / 100;
  }
  return out;
}

function fileBase(r: Report) {
  return `${r.title.replace(/[^a-z0-9]+/gi, "-").toLowerCase()}-${r.periodStart}-to-${r.periodEnd}`;
}

export async function exportReportPdf(r: Report, generatedBy: string) {
  const { jsPDF } = await import("jspdf");
  const { default: autoTable } = await import("jspdf-autotable");
  const landscape = r.columns.length > 6;
  const doc = new jsPDF({ unit: "pt", format: "a4", orientation: landscape ? "landscape" : "portrait" });
  const W = doc.internal.pageSize.getWidth();
  doc.setTextColor(20, 20, 20);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9.5);
  doc.text(COMPANY.name, 40, 48);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text(r.title, 40, 70);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text(`Period: ${fmtDate(r.periodStart)} - ${fmtDate(r.periodEnd)}`, W - 40, 52, { align: "right" });
  doc.text(`Printed: ${fmtDateTime(new Date())}`, W - 40, 66, { align: "right" });
  let y = 92;
  r.summary.forEach((s, i) => {
    const x = 40 + (i % 4) * ((W - 80) / 4);
    if (i && i % 4 === 0) y += 30;
    doc.setFontSize(8); doc.text(s.label, x, y);
    doc.setFont("helvetica", "bold"); doc.setFontSize(11); doc.text(s.value, x, y + 14); doc.setFont("helvetica", "normal");
  });
  const moneyIdx = r.columns.map((c, i) => (c.kind === "money" ? i : -1)).filter((i) => i >= 0);
  const totals = r.totals;
  autoTable(doc, {
    theme: "plain",
    startY: y + 32,
    head: [r.columns.map((c) => (c.kind === "money" ? `${c.label} (R)` : c.label))],
    body: r.rows.map((row) => r.columns.map((c) => cellText(c, row[c.key]))),
    ...(totals ? { foot: [r.columns.map((c, i) => (i === 0 ? "Totals" : c.kind === "money" ? statementAmount(totals[c.key] ?? 0) : ""))] } : {}),
    showFoot: "lastPage",
    styles: { fontSize: 8, cellPadding: 3, textColor: [20, 20, 20] },
    headStyles: { fontStyle: "bold", lineWidth: { bottom: 0.8 }, lineColor: [20, 20, 20] },
    footStyles: { fontStyle: "bold", lineWidth: { top: 0.8 }, lineColor: [20, 20, 20] },
    columnStyles: Object.fromEntries(moneyIdx.map((i) => [i, { halign: "right" as const }])),
    didParseCell: (data) => {
      if (data.section !== "body" && moneyIdx.includes(data.column.index)) data.cell.styles.halign = "right";
    },
    margin: { left: 40, right: 40, bottom: 50 },
  });
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    const H = doc.internal.pageSize.getHeight();
    doc.setFontSize(7.5);
    doc.text(`Generated by ${generatedBy}. Confidential - contains personal information protected under POPIA.`, 40, H - 24);
    doc.text(`Page ${i} of ${pages}`, W - 40, H - 24, { align: "right" });
  }
  doc.save(`${fileBase(r)}.pdf`);
}

export async function exportReportExcel(r: Report) {
  const ExcelJS = (await import("exceljs")).default;
  const wb = new ExcelJS.Workbook();
  wb.creator = COMPANY.name;
  const ws = wb.addWorksheet(r.title.slice(0, 31));
  ws.addRow([COMPANY.name]).font = { bold: true };
  ws.addRow([r.title]).font = { bold: true, size: 14 };
  ws.addRow([`Period: ${fmtDate(r.periodStart)} - ${fmtDate(r.periodEnd)}`]);
  r.summary.forEach((s) => ws.addRow([s.label, s.value]));
  ws.addRow([]);
  const head = ws.addRow(r.columns.map((c) => (c.kind === "money" ? `${c.label} (R)` : c.label)));
  head.font = { bold: true };
  head.eachCell((cell) => (cell.border = { bottom: { style: "thin" } }));
  for (const row of r.rows) {
    ws.addRow(r.columns.map((c) => (c.kind === "money" ? Number(row[c.key] ?? 0) : cellText(c, row[c.key]))));
  }
  if (r.totals) {
    const t = r.totals;
    const tr = ws.addRow(r.columns.map((c, i) => (i === 0 ? "Totals" : c.kind === "money" ? (t[c.key] ?? 0) : "")));
    tr.font = { bold: true };
    tr.eachCell((cell) => (cell.border = { top: { style: "thin" } }));
  }
  r.columns.forEach((c, i) => {
    const col = ws.getColumn(i + 1);
    col.width = c.kind === "money" ? 16 : c.kind === "date" ? 12 : 24;
    if (c.kind === "money") col.numFmt = "#,##0.00";
  });
  const buf = await wb.xlsx.writeBuffer();
  const url = URL.createObjectURL(new Blob([buf], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = `${fileBase(r)}.xlsx`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
